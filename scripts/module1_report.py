"""Module 1 report: dataset statistics and figures from the split manifests.

    python scripts/module1_report.py --xray data/manifests/xray_split.csv \
        --ct data/manifests/ct_split.csv --out reports/module1

Writes:
    data_stats.md              tables to paste into slides / the report
    fig_class_counts_<m>.png   positives per disease and split
    fig_images_per_patient.png why we split by patient
    fig_samples_<m>.png        one example image per disease
"""
from __future__ import annotations

import argparse
from pathlib import Path

import cv2
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

BASE = {"path", "patient_id", "source", "modality", "split", "view", "phash"}


def labels_of(df: pd.DataFrame) -> list[str]:
    return [c for c in df.columns if c not in BASE]


def table_md(df: pd.DataFrame) -> str:
    return df.to_markdown(index=False)


def section(name: str, df: pd.DataFrame, out: Path) -> str:
    labs = labels_of(df)
    lines = [f"## {name}", ""]
    lines.append(f"- Images: **{len(df):,}**  ·  Patients: **{df['patient_id'].nunique():,}**  ·  "
                 f"Datasets: {', '.join(sorted(df['source'].unique()))}")
    leak = (df.groupby("patient_id")["split"].nunique() > 1).sum()
    lines.append(f"- Patients appearing in more than one split: **{leak}** (must be 0)")
    lines.append("")

    split_tab = (df.groupby(["split"]).agg(images=("path", "size"), patients=("patient_id", "nunique"))
                 .reindex([s for s in ["train", "val", "test", "external"] if s in set(df["split"])]).reset_index())
    lines += ["### Images and patients per split", "", table_md(split_tab), ""]

    src_tab = df.groupby(["source", "split"]).size().unstack(fill_value=0).reset_index()
    lines += ["### Images per dataset and split", "", table_md(src_tab), ""]

    rows = []
    for lab in labs:
        r = {"disease": lab}
        for sp in ["train", "val", "test", "external"]:
            g = df[df["split"] == sp]
            if len(g):
                r[f"{sp} +"] = int((g[lab] == 1).sum())
                r[f"{sp} -"] = int((g[lab] == 0).sum())
        r["not labelled"] = int((df[lab] == -1).sum())
        rows.append(r)
    lines += ["### Positive (+) and negative (-) images per disease", "",
              "Images from datasets that don't label a disease are counted as *not labelled* and are ignored in training for that disease.", "",
              table_md(pd.DataFrame(rows)), ""]

    # figure: positives per disease per split
    pos = pd.DataFrame({sp: [int(((df["split"] == sp) & (df[l] == 1)).sum()) for l in labs]
                        for sp in ["train", "val", "test"] if (df["split"] == sp).any()}, index=labs)
    ax = pos.plot.barh(figsize=(7, 0.5 * len(labs) + 1.5), width=0.8)
    ax.set_xlabel("positive images")
    ax.set_title(f"{name}: positive images per disease")
    plt.tight_layout()
    f = out / f"fig_class_counts_{name.split()[0].lower()}.png"
    plt.savefig(f, dpi=160)
    plt.close()
    lines += [f"![class counts]({f.name})", ""]

    # figure: one sample per disease
    fig, axes = plt.subplots(1, len(labs), figsize=(2.6 * len(labs), 2.9))
    axes = [axes] if len(labs) == 1 else axes
    for ax, lab in zip(axes, labs):
        p = df[df[lab] == 1]
        ax.axis("off")
        ax.set_title(lab, fontsize=10)
        if len(p):
            img = cv2.imread(p.sample(1, random_state=1)["path"].iloc[0], cv2.IMREAD_GRAYSCALE)
            if img is not None:
                ax.imshow(img, cmap="gray")
    plt.tight_layout()
    f = out / f"fig_samples_{name.split()[0].lower()}.png"
    plt.savefig(f, dpi=140)
    plt.close()
    lines += [f"![samples]({f.name})", ""]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--xray", default=None)
    ap.add_argument("--ct", default=None)
    ap.add_argument("--out", default="reports/module1")
    args = ap.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    parts = ["# Module 1: dataset statistics", "",
             "Generated by `scripts/module1_report.py` from the split manifests after duplicate removal and patient-level splitting.", ""]
    ipp = {}
    for name, path in (("X-ray", args.xray), ("CT", args.ct)):
        if path and Path(path).exists():
            df = pd.read_csv(path)
            parts.append(section(name, df, out))
            ipp[name] = df.groupby("patient_id").size()

    if ipp:
        fig, axes = plt.subplots(1, len(ipp), figsize=(5 * len(ipp), 3.2))
        axes = [axes] if len(ipp) == 1 else axes
        for ax, (name, s) in zip(axes, ipp.items()):
            s.clip(upper=30).plot.hist(bins=30, ax=ax)
            ax.set_title(f"{name}: images per patient (capped at 30)")
            ax.set_xlabel("images")
        plt.tight_layout()
        plt.savefig(out / "fig_images_per_patient.png", dpi=160)
        plt.close()
        parts += ["## Images per patient", "",
                  "Many patients have several images, which is why the split is done by patient: otherwise the same patient "
                  "could appear in training and test, and test accuracy would be inflated.", "",
                  "![images per patient](fig_images_per_patient.png)", ""]
        for name, s in ipp.items():
            parts.append(f"- {name}: median {s.median():.0f}, max {s.max():,} images per patient")
    (out / "data_stats.md").write_text("\n".join(parts) + "\n")
    print(f"Wrote {out / 'data_stats.md'} and figures")


if __name__ == "__main__":
    main()
